import { notFound } from 'next/navigation'
import type { Metadata } from 'next'
import Link from 'next/link'
import { CheckCircle, MessageCircle, Truck } from 'lucide-react'
import { getOrderByToken } from '@/lib/store'
import { OrderStatusBadge } from '@/components/storefront/OrderStatusBadge'
import { OrderTimeline } from '@/components/storefront/OrderTimeline'
import { formatMAD } from '@/lib/utils'
import { formatMoroccanPhone, whatsappNumber } from '@/lib/phone'

/**
 * Server-rendered order confirmation page.
 *
 * Authorized solely by the unguessable `tracking_token` (UUID without dashes)
 * generated by `place_order_rpc`. No sequential IDs, no public order numbers.
 * Fetches the order server-side via the service-role client; never exposes
 * privileged credentials to the browser. Not cached.
 */
export const dynamic = 'force-dynamic'

export async function generateMetadata({
  params,
}: {
  params: Promise<{ token: string }>
}): Promise<Metadata> {
  const { token } = await params
  const result = await getOrderByToken(token)
  if (!result) {
    return { title: 'Commande introuvable | SAIS Store' }
  }
  return {
    title: `Commande ${result.orderNumber} | SAIS Store`,
    description: `Confirmation de votre commande ${result.orderNumber}. Total ${formatMAD(result.total)}. Paiement à la livraison.`,
  }
}

export default async function ConfirmationPage({
  params,
}: {
  params: Promise<{ token: string }>
}) {
  const { token } = await params
  const order = await getOrderByToken(token)

  if (!order) {
    notFound()
  }

  const firstName = order.customerName.split(' ')[0] ?? ''
  const whatsappText = encodeURIComponent(
    `Bonjour SAIS 👋\nJe viens de passer la commande ${order.orderNumber}.\n\nTotal à payer à la livraison : ${formatMAD(order.total)}\nMerci de me confirmer la livraison.`
  )

  return (
    <div className="mx-auto w-full max-w-2xl px-fib-3 py-fib-6 md:px-fib-4 md:py-fib-8">
      <section className="rounded-[24px] bg-white p-6 shadow-sm ring-1 ring-hairline md:p-8">
        <div className="flex items-start gap-3">
          <span className="flex h-11 w-11 shrink-0 items-center justify-center rounded-full bg-primary/10 text-primary">
            <CheckCircle size={22} />
          </span>
          <div>
            <p className="text-eyebrow uppercase text-text-muted">Commande enregistrée</p>
            <h1 className="mt-1 text-title text-ink">Merci {firstName}.</h1>
          </div>
        </div>

        <div className="mt-fib-3 rounded-2xl bg-surface-soft p-fib-3">
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div>
              <p className="text-eyebrow uppercase text-text-muted">Votre référence</p>
              <p className="mt-0.5 font-mono text-lg font-semibold tracking-wide text-ink">
                {order.orderNumber}
              </p>
            </div>
            <div className="text-end">
              <p className="text-eyebrow uppercase text-text-muted">Total à payer</p>
              <p className="mt-0.5 text-lg font-semibold text-ink">
                {formatMAD(order.total)}
              </p>
            </div>
          </div>
          <p className="mt-2 text-xs leading-relaxed text-text-muted">
            Gardez cette référence : elle suffit, avec votre téléphone, pour suivre la commande.
            Paiement en espèces à la réception.
          </p>
        </div>

        <div className="mt-fib-3">
          <OrderStatusBadge status={order.status} />
        </div>

        <div className="mt-fib-3">
          <OrderTimeline status={order.status} />
        </div>

        <ul className="mt-fib-4 divide-y divide-hairline rounded-2xl bg-surface-soft p-3">
          {order.items.map((item, index) => (
            <li
              key={`${item.slug}-${item.size ?? ''}-${item.color ?? ''}-${index}`}
              className="flex justify-between gap-4 py-3 text-sm"
            >
              <span className="min-w-0 text-text-muted">
                <span className="block truncate font-medium text-ink">{item.title}</span>
                <span>
                  {[item.color, item.size].filter(Boolean).join(' · ') || 'Sans variante'} · Qté{' '}
                  {item.quantity}
                </span>
              </span>
              <span className="shrink-0 font-medium text-ink">
                {formatMAD(item.price * item.quantity)}
              </span>
            </li>
          ))}
          <li className="mt-3 pt-3 border-t border-hairline flex justify-between text-sm">
            <span className="text-text-muted">Total</span>
            <span className="font-semibold text-ink">{formatMAD(order.total)}</span>
          </li>
        </ul>

        <p className="mt-fib-3 text-sm leading-relaxed text-text-muted">
          Nous vous appelons au{' '}
          <strong className="text-ink">{formatMoroccanPhone(order.phone)}</strong> pour
          confirmer l’adresse. Vous pouvez aussi nous envoyer le récapitulatif sur WhatsApp.
        </p>

        <div className="mt-fib-3 flex flex-col gap-2 sm:flex-row">
          <a
            href={`https://wa.me/${whatsappNumber(order.phone)}?text=${whatsappText}`}
            target="_blank"
            rel="noreferrer"
            className="press inline-flex h-12 items-center justify-center gap-2 rounded-full bg-primary px-6 text-sm font-medium text-white hover:bg-primary-light"
          >
            <MessageCircle size={16} />
            Envoyer sur WhatsApp
          </a>
          <Link
            href="/suivre"
            className="press inline-flex h-12 items-center justify-center rounded-full border border-hairline px-6 text-sm font-medium text-ink hover:bg-surface-soft"
          >
            Suivre ma commande
          </Link>
          <Link
            href="/boutique"
            className="press inline-flex h-12 items-center justify-center rounded-full px-6 text-sm font-medium text-text-muted hover:text-ink"
          >
            Continuer mes achats
          </Link>
        </div>

        <p className="mt-fib-4 text-xs text-text-muted">
          <Truck size={12} /> Livraison 24–48h partout au Maroc · Paiement en espèces à la
          réception.
        </p>
      </section>
    </div>
  )
}
