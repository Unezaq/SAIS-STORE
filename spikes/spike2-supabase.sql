-- SPIKE 2: Supabase Schema, RLS Policies, and Storage Policies
-- Verification of:
-- 1. Table creation with RLS
-- 2. Read as anon (public)
-- 3. Write as authenticated
-- 4. Admin-only policy using app_metadata custom claim
-- 5. Storage bucket and policies

-- Create role enum and user_roles table for Custom Claims pattern
create type public.app_role as enum ('admin', 'customer');

create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  role app_role not null default 'customer',
  created_at timestamptz default now(),
  unique (user_id, role)
);

alter table public.user_roles enable row level security;

-- Only admins can read/write user roles table
create policy "Admins can manage user roles"
  on public.user_roles
  for all
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'user_role') = 'admin');

-- 1. Test Products Table (Anon read, Admin write)
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text unique not null,
  price numeric(10,2) not null check (price >= 0),
  description text,
  is_active boolean default true,
  created_at timestamptz default now()
);

alter table public.products enable row level security;

-- Anon read policy
create policy "Anyone can read active products"
  on public.products
  for select
  to anon, authenticated
  using (is_active = true);

-- Admin write policy (insert, update, delete)
create policy "Admins can insert products"
  on public.products
  for insert
  to authenticated
  with check ((select auth.jwt() -> 'app_metadata' ->> 'user_role') = 'admin');

create policy "Admins can update products"
  on public.products
  for update
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'user_role') = 'admin');

create policy "Admins can delete products"
  on public.products
  for delete
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'user_role') = 'admin');

-- 2. Orders Table (Authenticated write own, Authenticated read own, Admin read/update all)
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  customer_phone text not null,
  shipping_address text not null,
  total_amount numeric(10,2) not null check (total_amount >= 0),
  status text not null default 'pending', -- pending, confirmed, shipped, delivered, cancelled
  created_at timestamptz default now()
);

alter table public.orders enable row level security;

-- Customers can create orders (authenticated or anon guest checkout with server action)
create policy "Authenticated users can create orders"
  on public.orders
  for insert
  to authenticated
  with check (auth.uid() = customer_id);

-- Customers can view their own orders
create policy "Users can view own orders"
  on public.orders
  for select
  to authenticated
  using (auth.uid() = customer_id or (select auth.jwt() -> 'app_metadata' ->> 'user_role') = 'admin');

-- Admins can update any order status
create policy "Admins can update order status"
  on public.orders
  for update
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'user_role') = 'admin');

-- 3. Storage bucket and policy for product images
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

create policy "Public can view product images"
  on storage.objects
  for select
  to public
  using (bucket_id = 'product-images');

create policy "Admins can upload product images"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'product-images' and
    (select auth.jwt() -> 'app_metadata' ->> 'user_role') = 'admin'
  );

